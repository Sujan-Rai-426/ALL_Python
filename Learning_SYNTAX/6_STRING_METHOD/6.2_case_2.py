
text = "python programming is fun"


# NOTE: title(): Capitalizes the first letter of each word.
print(text.title())  # Output: Python Programming Is Fun

# NOTE: capitalize(): Capitalizes only the first character of the string.
print(text.capitalize())  # Output: Python programming is fun

# NOTE: swapcase(): Swaps uppercase characters to lowercase and vice versa.
new_text = "PythoN 3.10"
print(new_text.swapcase())  # Output: pYTHOn 3.10