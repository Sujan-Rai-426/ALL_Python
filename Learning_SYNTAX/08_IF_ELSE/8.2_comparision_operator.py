# Equal to (==)
name = "John"
if name == "John":
    print("Hello John!")  # Output: Hello John!

# Not equal (!=)
password = "12345"
if password != "admin":
    print("Password is not admin")  # Output: Password is not admin

# Greater than (>)
age = 25
if age > 18:
    print("Adult")  # Output: Adult

# Less than (<)
temperature = -5
if temperature < 0:
    print("Freezing!")  # Output: Freezing!

# Greater than or equal (>=)
score = 75
if score >= 60:
    print("Pass")  # Output: Pass

# Less than or equal (<=)
children = 2
if children <= 3:
    print("Small family")  # Output: Small family

# Compare strings (case-sensitive)
if "Hello" == "hello":
    print("Same")
else:
    print("Different")  # Output: Different

# Case-insensitive comparison
if "Hello".lower() == "hello":
    print("Same after lower()")  # Output: Same after lower()